def get_concise_meaning(word: str, old_meaning: str) -> str:
    """Tạo nghĩa tiếng Việt ngắn gọn (3-8 từ)"""
    w_lower = word.lower().strip()
    if w_lower in COMMON_VIETNAMESE:
        return COMMON_VIETNAMESE[w_lower]
    
    # Nếu old_meaning quá dài (>60 chars), trích đoạn ngắn hoặc dọn dẹp
    if old_meaning and len(old_meaning) > 0:
        cleaned = old_meaning.strip()
        # Loại bỏ các đoạn định nghĩa tiếng Anh dài dòng
        if cleaned.startswith("The amount by") or len(cleaned) > 80:
            return f"Từ vựng '{word}'"
        return cleaned[:60]
    
    return f"Nghĩa từ '{word}'"

async def fetch_ipa_online(client: httpx.AsyncClient, word: str) -> str:
    """Lấy IPA ngắn gọn từ Free Dictionary API"""
    url = f"https://api.dictionaryapi.dev/api/v2/entries/en/{urllib.parse.quote(word)}"
    try:
        resp = await client.get(url, timeout=3.5)
        if resp.status_code == 200:
            data = resp.json()
            if isinstance(data, list) and len(data) > 0:
                phonetics = data[0].get("phonetics", [])
                for ph in phonetics:
                    txt = ph.get("text")
                    if txt and "/" in txt:
                        return txt
                if data[0].get("phonetic"):
                    return data[0].get("phonetic")
    except Exception:
        pass
    return ""

async def translate_gtx(client: httpx.AsyncClient, text: str) -> str:
    """Dịch nhanh từ/cụm từ sang tiếng Việt ngắn gọn qua Google Translate GTX"""
    if not text or len(text) > 80:
        return ""
    url = f"https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=vi&dt=t&q={urllib.parse.quote(text)}"
    try:
        resp = await client.get(url, timeout=3.5)
        if resp.status_code == 200:
            res_data = resp.json()
            if isinstance(res_data, list) and len(res_data) > 0 and isinstance(res_data[0], list):
                pieces = [p[0] for p in res_data[0] if p and p[0]]
                if pieces:
                    translated = "".join(pieces).strip().lower()
                    if len(translated) <= 60:
                        return translated
    except Exception:
        pass
    return ""

async def process_word_doc(doc, http_client, sem):
    async with sem:
        doc_id = doc["_id"]
        word = doc.get("word", "").strip()
        old_meaning = doc.get("meaning", "") or ""
        old_ipa = doc.get("ipa", "") or ""

        # 1. Concise Vietnamese meaning
        new_meaning = ""
        word_lower = word.lower()

        if word_lower in COMMON_VIETNAMESE:
            new_meaning = COMMON_VIETNAMESE[word_lower]
        elif old_meaning and not old_meaning.startswith("The amount") and not old_meaning.startswith("Nghĩa từ vựng") and len(old_meaning) <= 50:
            new_meaning = old_meaning
        else:
            gtx_trans = await translate_gtx(http_client, word)
            if gtx_trans:
                new_meaning = gtx_trans
            else:
                new_meaning = get_concise_meaning(word, old_meaning)

        # 2. IPA
        new_ipa = old_ipa
        if not new_ipa or len(new_ipa) < 2:
            online_ipa = await fetch_ipa_online(http_client, word)
            if online_ipa:
                new_ipa = online_ipa

        if new_meaning != old_meaning or new_ipa != old_ipa:
            return UpdateOne({"_id": doc_id}, {"$set": {"meaning": new_meaning, "ipa": new_ipa}})
        return None

async def main():
    print("🚀 Bắt đầu làm sạch & bổ sung Nghĩa Tiếng Việt ngắn gọn + IPA song song cho MongoDB...")
    client = MongoClient(MONGO_URI)
    db = client[DATABASE_NAME]
    words_col = db["words"]

    all_words = list(words_col.find({}, {"_id": 1, "word": 1, "meaning": 1, "ipa": 1, "word_type": 1}))
    print(f"Tổng số từ vựng trong MongoDB: {len(all_words)}")

    sem = asyncio.Semaphore(20)
    limits = httpx.Limits(max_keepalive_connections=20, max_connections=30)
    async with httpx.AsyncClient(headers={"User-Agent": "OmniEnglish/1.0"}, limits=limits) as http_client:
        tasks = [process_word_doc(doc, http_client, sem) for doc in all_words]
        results = await asyncio.gather(*tasks)

        bulk_ops = [r for r in results if r is not None]
        if bulk_ops:
            words_col.bulk_write(bulk_ops, ordered=False)
            print(f"✅ Đã làm sạch & cập nhật thành công {len(bulk_ops)} từ vựng trong MongoDB!")
        else:
            print("✅ Tất cả từ vựng đã được làm sạch đầy đủ!")

    client.close()

if __name__ == "__main__":
    asyncio.run(main())
